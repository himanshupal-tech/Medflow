// Map dedicated translations
const dedicatedTranslations = {
  en: enIntake,
  hi: hiIntake,
  bn: bnIntake,
  mr: mrIntake,
  ta: taIntake,
  te: teIntake,
  gu: guIntake,
};

/**
 * Applies structured intake translations to all registered i18n languages.
 * Languages with dedicated dictionaries receive localized strings;
 * all others receive the complete english fallback so no key is ever missing.
 */
export function applyIntakeTranslations(resources) {
  if (!resources || typeof resources !== "object") return;

  const enFull = resources.en && resources.en.translation ? resources.en.translation : {};

  for (const lang of Object.keys(resources)) {
    if (!resources[lang]) resources[lang] = {};
    if (!resources[lang].translation) resources[lang].translation = {};

    // If a language had an empty translation table (e.g. sw), seed with complete english resources
    if (Object.keys(resources[lang].translation).length === 0 && lang !== "en") {
      deepMerge(resources[lang].translation, enFull);
    }

    // Merge baseline English intake translations
    deepMerge(resources[lang].translation, enIntake);

    // If dedicated language translation exists, overlay it
    if (dedicatedTranslations[lang]) {
      const dedicated = dedicatedTranslations[lang];
      deepMerge(resources[lang].translation, dedicated);

      // Dedicated dictionaries predate the document step. Reuse their existing
      // AI and review translations at the new positions, while the new document
      // strings remain available through the English baseline for every language.
      const legacyFlow = dedicated.intakeFlow;
      if (legacyFlow) {
        const flow = resources[lang].translation.intakeFlow;
        flow.stepBadge5 = enIntake.intakeFlow.stepBadge5;
        flow.stepLabel5 = enIntake.intakeFlow.stepLabel5;
        flow.step5Title = enIntake.intakeFlow.step5Title;
        flow.step5Subtitle = enIntake.intakeFlow.step5Subtitle;
        flow.stepBadge6 = legacyFlow.stepBadge5 || flow.stepBadge6;
        flow.stepBadge7 = legacyFlow.stepBadge6 || flow.stepBadge7;
        flow.stepLabel6 = legacyFlow.stepLabel5 || flow.stepLabel6;
        flow.stepLabel7 = legacyFlow.stepLabel6 || flow.stepLabel7;
        flow.step6Title = legacyFlow.step5Title || flow.step6Title;
        flow.step6Subtitle = legacyFlow.step5Subtitle || flow.step6Subtitle;
        flow.step7Title = legacyFlow.step6Title || flow.step7Title;
        flow.step7Subtitle = legacyFlow.step6Subtitle || flow.step7Subtitle;
      }
    }
  }
}
